export interface LexaraClipMotion {
  headX: number;
  headY: number;
  jaw: number;
  width: number;
}

export function sampleLexaraClipMotion(
  playbackTimeSec: number,
  turnId: string | null | undefined,
  audioOpen: number,
  audioWide: number,
): LexaraClipMotion {
  let hash = 0;
  for (let i = 0; i < (turnId?.length ?? 0); i++) {
    hash = ((hash * 31) + turnId!.charCodeAt(i)) | 0;
  }
  const clip = CLIPS[(hash >>> 0) % CLIPS.length];
  const phase = Math.floor(Math.max(0, playbackTimeSec) * CLIP_FPS) % clip.length;
  const motion = clip[phase];
  // Select the closest sampled mouth geometry to the current audio, never a
  // pre-recorded lip timeline that would drift away from the spoken words.
  let match = motion;
  let best = Number.POSITIVE_INFINITY;
  for (const pose of clip) {
    const distance = Math.abs(pose[2] - audioOpen) * 1.3 + Math.abs(pose[3] - audioWide);
    if (distance < best) { best = distance; match = pose; }
  }
  return {
    headX: Math.max(-1, Math.min(1, motion[0] / 5)),
    headY: Math.max(-1, Math.min(1, motion[1] / 5)),
    jaw: match[2],
    width: match[3],
  };
}
