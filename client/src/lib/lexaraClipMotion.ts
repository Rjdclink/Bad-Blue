export interface LexaraClipMotion {
  headX: number;
  headY: number;
  jaw: number;
  width: number;
}

export function sampleLexaraClipMotion(
  playbackTimeSec: number,
  turnId: string | null | undefined,
  audioOpen: number,
  audioWide: number,
): LexaraClipMotion {
  let hash = 0;
  for (let i = 0; i < (turnId?.length ?? 0); i++) {
    hash = ((hash * 31) + turnId!.charCodeAt(i)) | 0;
  }
  const clip = CLIPS[(hash >>> 0) % CLIPS.length];
  const position = (Number.isFinite(playbackTimeSec) ? Math.max(0, playbackTimeSec) : 0) * CLIP_FPS;
  const index = Math.floor(position) % clip.length;
  const blend = position - Math.floor(position);
  const current = clip[index];
  const next = clip[(index + 1) % clip.length];
  const open = Number.isFinite(audioOpen) ? Math.max(0, Math.min(1, audioOpen)) : 0;
  const wide = Number.isFinite(audioWide) ? Math.max(0, Math.min(1, audioWide)) : 0;
  const openCell = Math.round(open * 15);
  const wideCell = Math.round(wide * 15);
  const [firstIndex, secondIndex] = POSE_GRID[openCell * 16 + wideCell];
  const first = POSES[firstIndex];
  const second = POSES[secondIndex];
  const firstDistance = Math.hypot(first[2] - open, first[3] - wide) + 0.001;
  const secondDistance = Math.hypot(second[2] - open, second[3] - wide) + 0.001;
  const firstWeight = secondDistance / (firstDistance + secondDistance);
  const mix = (a: number, b: number) => a * firstWeight + b * (1 - firstWeight);
  const headMix = (axis: 0 | 1) =>
    Math.max(-1, Math.min(1, (current[axis] + (next[axis] - current[axis]) * blend) / 5));
  return {
    headX: headMix(0),
    headY: headMix(1),
    jaw: mix(first[2], second[2]),
    width: mix(first[3], second[3]),
  };
}
